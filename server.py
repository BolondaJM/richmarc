"""
Richmarc site server with admin API (Python 3 standard library only).

    python server.py            # serves http://localhost:5173
    python server.py 8080       # custom port

- Serves the static site.
- /admin/ is the admin panel. First login: admin / admin (change it in the panel).
- Content is stored in data/content.json. Every save regenerates js/content.js,
  so the public pages stay plain static files and can be hosted anywhere.
- Credentials are stored hashed (PBKDF2) in data/admin.json, which is never served.
"""

import base64
import hashlib
import hmac
import json
import os
import re
import secrets
import shutil
import sys
import time
from http import HTTPStatus
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import urlparse

ROOT = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(ROOT, "data")
CONTENT_FILE = os.path.join(DATA_DIR, "content.json")
BACKUP_DIR = os.path.join(DATA_DIR, "backups")
ADMIN_FILE = os.path.join(DATA_DIR, "admin.json")
CONTENT_JS = os.path.join(ROOT, "js", "content.js")
UPLOAD_DIR = os.path.join(ROOT, "assets", "uploads")

SESSION_COOKIE = "rm_admin"
SESSION_TTL = 8 * 60 * 60  # 8 hours
MAX_BODY = 12 * 1024 * 1024  # 12 MB (uploads arrive base64 encoded)
MAX_UPLOAD = 8 * 1024 * 1024
ALLOWED_IMAGE_EXT = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif"}
BLOCKED_PREFIXES = ("/data", "/server.py", "/.git", "/.claude", "/.agents", "/skills-lock.json")

SESSIONS = {}  # token -> {"user": str, "expires": float}
LOGIN_FAILS = {}  # ip -> [timestamps]


# ---------------------------------------------------------------------------
# Credentials
# ---------------------------------------------------------------------------

def hash_password(password, salt=None):
    salt = salt or secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, 200_000)
    return base64.b64encode(salt).decode(), base64.b64encode(digest).decode()


def load_admin():
    if not os.path.exists(ADMIN_FILE):
        # Seed the first test account: admin / admin
        salt, digest = hash_password("admin")
        save_admin({"username": "admin", "salt": salt, "hash": digest, "default": True})
    with open(ADMIN_FILE, encoding="utf-8") as f:
        return json.load(f)


def save_admin(record):
    os.makedirs(DATA_DIR, exist_ok=True)
    with open(ADMIN_FILE, "w", encoding="utf-8") as f:
        json.dump(record, f, indent=2)


def check_credentials(username, password):
    rec = load_admin()
    _, digest = hash_password(password, base64.b64decode(rec["salt"]))
    user_ok = hmac.compare_digest(username.encode(), rec["username"].encode())
    pass_ok = hmac.compare_digest(digest, rec["hash"])
    return user_ok and pass_ok


# ---------------------------------------------------------------------------
# Content
# ---------------------------------------------------------------------------

def read_content():
    with open(CONTENT_FILE, encoding="utf-8") as f:
        return json.load(f)


def validate_content(c):
    if not isinstance(c, dict):
        return "Content must be an object."
    for key in ("properties", "stats", "testimonials", "faqs", "buildTiers", "buildExtras"):
        if not isinstance(c.get(key), list):
            return f"'{key}' must be a list."
    if not isinstance(c.get("settings"), dict):
        return "'settings' must be an object."
    ids = set()
    for p in c["properties"]:
        pid = p.get("id", "")
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", pid or ""):
            return f"Home id '{pid}' must be lowercase letters, numbers and dashes."
        if pid in ids:
            return f"Two homes share the id '{pid}'."
        ids.add(pid)
        if not p.get("name"):
            return f"Home '{pid}' needs a name."
    if not c["buildTiers"]:
        return "Keep at least one build tier for the estimator."
    return None


def write_content(c):
    os.makedirs(BACKUP_DIR, exist_ok=True)
    if os.path.exists(CONTENT_FILE):
        stamp = time.strftime("%Y%m%d-%H%M%S")
        shutil.copy2(CONTENT_FILE, os.path.join(BACKUP_DIR, f"content-{stamp}.json"))
        backups = sorted(os.listdir(BACKUP_DIR))
        for old in backups[:-30]:  # keep the 30 most recent
            os.remove(os.path.join(BACKUP_DIR, old))
    text = json.dumps(c, indent=2, ensure_ascii=False)
    tmp = CONTENT_FILE + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, CONTENT_FILE)
    # "</" is escaped so text such as "</script>" can never break out of the script.
    js_text = text.replace("</", "<\\/")
    with open(CONTENT_JS, "w", encoding="utf-8") as f:
        f.write(
            "/* Generated by the admin panel (server.py) from data/content.json. Do not edit by hand. */\n"
            f"window.RICHMARC_CONTENT = {js_text};\n"
        )


# ---------------------------------------------------------------------------
# HTTP handler
# ---------------------------------------------------------------------------

class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=ROOT, **kwargs)

    # ---- helpers ----
    def send_json(self, status, payload, extra_headers=None):
        body = json.dumps(payload).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        for k, v in (extra_headers or {}).items():
            self.send_header(k, v)
        self.end_headers()
        self.wfile.write(body)

    def read_json(self):
        length = int(self.headers.get("Content-Length") or 0)
        if length > MAX_BODY:
            raise ValueError("Request is too large.")
        raw = self.rfile.read(length) if length else b"{}"
        return json.loads(raw.decode("utf-8"))

    def session_token(self):
        cookie = self.headers.get("Cookie", "")
        m = re.search(rf"(?:^|;\s*){SESSION_COOKIE}=([A-Za-z0-9_\-]+)", cookie)
        return m.group(1) if m else None

    def current_user(self):
        token = self.session_token()
        s = SESSIONS.get(token) if token else None
        if not s or s["expires"] < time.time():
            SESSIONS.pop(token, None)
            return None
        s["expires"] = time.time() + SESSION_TTL
        return s["user"]

    def same_origin(self):
        # Blocks cross-site form posts against the API (CSRF).
        origin = self.headers.get("Origin")
        if not origin:
            return True
        return urlparse(origin).netloc == self.headers.get("Host")

    def end_headers(self):
        path = urlparse(self.path).path
        if path.endswith(".js") or path.endswith(".html") or path.endswith("/"):
            self.send_header("Cache-Control", "no-cache")
        if path.startswith("/admin"):
            self.send_header("X-Frame-Options", "DENY")
        super().end_headers()

    # ---- routing ----
    def do_GET(self):
        path = urlparse(self.path).path
        if any(path == p or path.startswith(p + "/") for p in BLOCKED_PREFIXES):
            return self.send_error(HTTPStatus.NOT_FOUND)
        if path == "/api/session":
            user = self.current_user()
            rec = load_admin()
            return self.send_json(200, {"user": user, "defaultPassword": bool(rec.get("default")) if user else None})
        if path == "/api/content":
            if not self.current_user():
                return self.send_json(401, {"error": "Sign in first."})
            return self.send_json(200, read_content())
        if path.startswith("/api/"):
            return self.send_json(404, {"error": "Not found."})
        return super().do_GET()

    def do_HEAD(self):
        path = urlparse(self.path).path
        if any(path == p or path.startswith(p + "/") for p in BLOCKED_PREFIXES):
            return self.send_error(HTTPStatus.NOT_FOUND)
        return super().do_HEAD()

    def do_POST(self):
        path = urlparse(self.path).path
        if not self.same_origin():
            return self.send_json(403, {"error": "Cross-site request blocked."})
        try:
            body = self.read_json()
        except (ValueError, json.JSONDecodeError) as e:
            return self.send_json(400, {"error": str(e) or "Invalid JSON."})

        if path == "/api/login":
            return self.login(body)
        if path == "/api/logout":
            SESSIONS.pop(self.session_token(), None)
            return self.send_json(200, {"ok": True}, {"Set-Cookie": f"{SESSION_COOKIE}=; Path=/; Max-Age=0; HttpOnly; SameSite=Strict"})

        user = self.current_user()
        if not user:
            return self.send_json(401, {"error": "Your session has ended. Sign in again."})

        if path == "/api/content":
            err = validate_content(body)
            if err:
                return self.send_json(400, {"error": err})
            write_content(body)
            return self.send_json(200, {"ok": True})
        if path == "/api/password":
            return self.change_password(body)
        if path == "/api/upload":
            return self.upload(body)
        return self.send_json(404, {"error": "Not found."})

    # ---- actions ----
    def login(self, body):
        ip = self.client_address[0]
        now = time.time()
        fails = [t for t in LOGIN_FAILS.get(ip, []) if now - t < 300]
        if len(fails) >= 8:
            return self.send_json(429, {"error": "Too many attempts. Wait five minutes and try again."})
        username = str(body.get("username", ""))
        password = str(body.get("password", ""))
        if not check_credentials(username, password):
            fails.append(now)
            LOGIN_FAILS[ip] = fails
            return self.send_json(401, {"error": "That username and password don't match."})
        LOGIN_FAILS.pop(ip, None)
        token = secrets.token_urlsafe(32)
        SESSIONS[token] = {"user": username, "expires": now + SESSION_TTL}
        cookie = f"{SESSION_COOKIE}={token}; Path=/; HttpOnly; SameSite=Strict; Max-Age={SESSION_TTL}"
        return self.send_json(200, {"user": username, "defaultPassword": bool(load_admin().get("default"))}, {"Set-Cookie": cookie})

    def change_password(self, body):
        rec = load_admin()
        current = str(body.get("current", ""))
        new_user = str(body.get("username", rec["username"])).strip() or rec["username"]
        new_pass = str(body.get("password", ""))
        if not check_credentials(rec["username"], current):
            return self.send_json(400, {"error": "Current password is incorrect."})
        if len(new_pass) < 8:
            return self.send_json(400, {"error": "Use at least 8 characters for the new password."})
        salt, digest = hash_password(new_pass)
        save_admin({"username": new_user, "salt": salt, "hash": digest, "default": False})
        # Sign out every other session
        token = self.session_token()
        for t in list(SESSIONS):
            if t != token:
                SESSIONS.pop(t)
        if token in SESSIONS:
            SESSIONS[token]["user"] = new_user
        return self.send_json(200, {"ok": True, "user": new_user})

    def upload(self, body):
        name = str(body.get("name", "image"))
        data_url = str(body.get("data", ""))
        m = re.match(r"data:image/[\w.+-]+;base64,(.+)$", data_url, re.S)
        ext = os.path.splitext(name)[1].lower()
        if not m or ext not in ALLOWED_IMAGE_EXT:
            return self.send_json(400, {"error": "Upload a JPG, PNG, WebP, GIF or AVIF image."})
        raw = base64.b64decode(m.group(1))
        if len(raw) > MAX_UPLOAD:
            return self.send_json(400, {"error": "Images must be 8 MB or smaller."})
        stem = re.sub(r"[^a-z0-9]+", "-", os.path.splitext(name)[0].lower()).strip("-")[:40] or "image"
        filename = f"{stem}-{secrets.token_hex(3)}{ext}"
        os.makedirs(UPLOAD_DIR, exist_ok=True)
        with open(os.path.join(UPLOAD_DIR, filename), "wb") as f:
            f.write(raw)
        return self.send_json(200, {"url": f"assets/uploads/{filename}"})


def main():
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 5173
    load_admin()
    if not os.path.exists(CONTENT_JS):
        write_content(read_content())
    server = ThreadingHTTPServer(("127.0.0.1", port), Handler)
    print(f"Richmarc running at http://localhost:{port}  (admin: http://localhost:{port}/admin/)")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
